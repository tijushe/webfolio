// Flashcard decks, built from the word lists in fwddutchwordlist.zip.
//
// HOW TO ADD/EDIT CARDS:
// Each deck's `cards` come from a plain [dutch, english] pair list, so you
// can just add a line like ["nieuwwoord", "new word"] to the right deck.
// To add a whole new deck, copy a deck object and give it a new `id`.

export type Flashcard = { front: string; back: string }
export type DeckColor = { bg: string; border: string; text: string }
export type Deck = {
  id: string
  title: string
  description: string
  color: DeckColor
  cards: Flashcard[]
}

function cards(pairs: [string, string][]): Flashcard[] {
  return pairs.map(([front, back]) => ({ front, back }))
}

// Opposite pairs -> two cross-referencing cards each: [wordA, meaningA, wordB, meaningB]
function opposites(pairs: [string, string, string, string][]): Flashcard[] {
  return pairs.flatMap(([a, ma, b, mb]) => [
    { front: a, back: `${ma}  (opposite: ${b} - ${mb})` },
    { front: b, back: `${mb}  (opposite: ${a} - ${ma})` },
  ])
}

